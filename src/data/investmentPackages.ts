// Category helpers
export const getPackagesByCategory = (category: 'premium' | 'standard' | 'basic') => {
  return investmentPackages.filter(pkg => pkg.category === category);
};

export const getHomePagePackages = () => {
  return investmentPackages.filter(pkg => pkg.showOnHome);
};

export const getCategoryStats = () => {
  const premium = getPackagesByCategory('premium');
  const standard = getPackagesByCategory('standard');
  const basic = getPackagesByCategory('basic');
  
  return {
    premium: {
      count: premium.length,
      totalValue: premium.reduce((sum, pkg) => sum + pkg.investmentAmount, 0)
    },
    standard: {
      count: standard.length,
      totalValue: standard.reduce((sum, pkg) => sum + pkg.investmentAmount, 0)
    },
    basic: {
      count: basic.length,
      totalValue: basic.reduce((sum, pkg) => sum + pkg.investmentAmount, 0)
    }
  };
};
